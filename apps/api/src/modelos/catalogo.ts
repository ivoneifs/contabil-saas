export interface ModeloDef {
  id: string;
  categoria: string;
  titulo: string;
}

function slug(texto: string) {
  return texto
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export const MODELOS: ModeloDef[] = Object.entries(CATEGORIAS).flatMap(([categoria, titulos]) =>
  titulos.map((titulo) => ({ id: slug(titulo), categoria, titulo })),
);
